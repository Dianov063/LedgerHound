export function translatePaymentSafety(locale: string, text: string): string {
  if (locale === 'en') return text;
  return PAYMENT_SAFETY_TRANSLATIONS[locale as Exclude<Locale, 'en'>]?.[text] || text;
}

/**
 * The API answers in English. A known message is shown in the page language;
 * anything else (dynamic or internal text) becomes the caller's fallback, which
 * is already translated.
 */
export function translateApiError(locale: string, error: unknown, fallback: string): string {
  if (typeof error !== 'string' || !error) return fallback;
  if (locale === 'en') return error;
  return PAYMENT_SAFETY_TRANSLATIONS[locale as Exclude<Locale, 'en'>]?.[error] || fallback;
}

